/**
 * Resolve a key in the given language: `en` keys missing from the EN dict fall
 * back to Thai; Thai is always present.
 */
export function translate(lang: "th" | "en", key: string, vars?: Record<string, string | number>): string {
  const dict: string = lang === "en" ? (en[key] ?? th[key] ?? key) : th[key] ?? key;
  return dict.replace(/\{(\w+)\}/g, (m, name) => (vars?.[name] !== undefined ? String(vars[name]) : m));
}
